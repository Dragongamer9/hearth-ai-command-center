// Every commit under the owner's name: env for runs, the attribution-stripping hook, the
// guard before publishing, the rewrite limits, lead releases/tags, and the saved setting.
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const id = require('../electron/ops/identity.cjs');
const rel = require('../electron/ops/release.cjs');

const OWNER = { name: 'Dragongamer9', email: 'Dragongamer9@users.noreply.github.com' };
const TRAILERS = ['Co-authored-by: Claude <noreply@anthropic.com>', 'Co-Authored-By: Claude Opus <noreply@anthropic.com>', 'CO-AUTHORED-BY: x <y@z.com>', 'Claude-Session: https://claude.ai/code/session_1', '🤖 Generated with [Claude Code](https://claude.com/claude-code)', 'Generated with Claude Code', 'Generated by Codex'];

test('identity: parsed, cleaned, and put in the git env for runs', () => {
  assert.deepEqual(id.parseIdentity('Dragongamer9 <Dragongamer9@users.noreply.github.com>'), OWNER);
  assert.equal(id.parseIdentity('no email'), null);
  assert.equal(id.cleanIdentity({ name: 'x', email: 'bad' }), null);
  assert.deepEqual(id.gitEnv(OWNER), { GIT_AUTHOR_NAME: OWNER.name, GIT_AUTHOR_EMAIL: OWNER.email, GIT_COMMITTER_NAME: OWNER.name, GIT_COMMITTER_EMAIL: OWNER.email });
  const index = fs.readFileSync(path.join(__dirname, '..', 'electron', 'ops', 'index.cjs'), 'utf8');
  assert.match(index, /return \{ HEARTH_AI_ASSETS: dir, \.\.\.identity\.gitEnv\(applyIdentity\(\)\) \};/, 'every AI run gets the owner env');
  assert.match(index, /Object\.assign\(process\.env, identity\.gitEnv\(id\)\)/, 'every app git operation inherits it');
  const main = fs.readFileSync(path.join(__dirname, '..', 'electron', 'main.cjs'), 'utf8');
  assert.match(main, /ownerIdentity: cleanIdentity\(s\.ownerIdentity\),/, 'saved and read back');
  assert.match(main, /if \('ownerIdentity' in patch\) s\.ownerIdentity = cleanIdentity\(patch\.ownerIdentity\);/);
});

test('the commit-msg hook strips every attribution trailer form (and the JS filter matches)', () => {
  const d = fs.mkdtempSync(path.join(os.tmpdir(), 'hook-'));
  const hook = path.join(d, 'commit-msg');
  fs.writeFileSync(hook, id.hookScript(), { mode: 0o755 });
  const msg = path.join(d, 'MSG');
  fs.writeFileSync(msg, ['Fix the Wi-Fi list', '', 'Rescan after resume.', '', ...TRAILERS, 'Signed-off-by: Dragongamer9 <Dragongamer9@users.noreply.github.com>'].join('\n'));
  execFileSync('sh', [hook, msg]);
  const out = fs.readFileSync(msg, 'utf8');
  for (const t of TRAILERS) assert.ok(!out.includes(t), t);
  assert.match(out, /Fix the Wi-Fi list\n\nRescan after resume\./);
  assert.match(out, /Signed-off-by: Dragongamer9/);
  for (const t of TRAILERS) assert.equal(id.hasTrailer(t), true, t);
  assert.equal(id.hasTrailer('Generated with care: a better resume flow'), false, 'ordinary words are kept');
  assert.equal(id.stripTrailers(`a\n\n${TRAILERS.join('\n')}\n`), 'a\n');
});

test('hooks are installed once, never over a hook the owner wrote', () => {
  const d = fs.mkdtempSync(path.join(os.tmpdir(), 'hooks-'));
  fs.writeFileSync(path.join(d, 'commit-msg'), '#!/bin/sh\necho mine\n');
  const r = id.installHooks(d);
  assert.deepEqual(r, { done: ['prepare-commit-msg'], skipped: ['commit-msg'] });
  assert.match(fs.readFileSync(path.join(d, 'commit-msg'), 'utf8'), /echo mine/);
  assert.deepEqual(id.installHooks(d).done, ['prepare-commit-msg'], 'ours is updated in place');
});

test('the guard refuses a foreign author, a foreign committer and a trailer; real git log', () => {
  const d = fs.mkdtempSync(path.join(os.tmpdir(), 'guard-'));
  const g = (args, env = {}) => execFileSync('git', args, { cwd: d, encoding: 'utf8', env: { ...process.env, ...env } });
  const as = (n, e) => ({ GIT_AUTHOR_NAME: n, GIT_AUTHOR_EMAIL: e, GIT_COMMITTER_NAME: n, GIT_COMMITTER_EMAIL: e });
  g(['init', '-q']);
  g(['commit', '-q', '--allow-empty', '-m', 'base'], as(OWNER.name, OWNER.email));
  g(['commit', '-q', '--allow-empty', '-m', 'mine'], as(OWNER.name, OWNER.email));
  const scan = () => id.scanCommits(id.parseLog(g(['log', id.LOG_FORMAT, 'HEAD~1..HEAD'])), OWNER);
  assert.equal(scan().ok, true);
  g(['commit', '-q', '--allow-empty', '-m', 'theirs'], as('Claude', 'noreply@anthropic.com'));
  assert.match(scan().problems.join(), /authored by Claude <noreply@anthropic\.com>/);
  g(['commit', '-q', '--allow-empty', '-m', 'x'], { ...as(OWNER.name, OWNER.email), GIT_COMMITTER_NAME: 'bot', GIT_COMMITTER_EMAIL: 'bot@x.io' });
  assert.match(scan().problems.join(), /committed by bot/);
  g(['commit', '-q', '--allow-empty', '--no-verify', '-m', 'Fix\n\nCo-Authored-By: Claude <noreply@anthropic.com>'], as(OWNER.name, OWNER.email));
  assert.match(scan().problems.join(), /AI attribution line/);
  assert.equal(id.scanCommits([], null).ok, false, 'no identity set: nothing is published');
});

test('the rewrite is confined to unpublished hearth/ task branches', () => {
  assert.equal(id.rewriteAllowed({ branch: 'hearth/abc123-wifi' }).ok, true);
  for (const b of ['main', 'master', 'release/next', 'feature/x', '']) assert.equal(id.rewriteAllowed({ branch: b }).ok, false, b);
  assert.match(id.rewriteAllowed({ branch: 'hearth/abc123', remoteBranchesContaining: ['origin/hearth/abc123'] }).reason, /already on GitHub/);
  const index = fs.readFileSync(path.join(__dirname, '..', 'electron', 'ops', 'index.cjs'), 'utf8');
  const rw = index.slice(index.indexOf("handle('ops:rewriteTask'"), index.indexOf('// ---- releases and tags'));
  assert.match(rw, /showMessageBoxSync/, 'owner confirms');
  assert.match(rw, /s\.leadActions !== true \|\| s\.leadMerge !== true/, 'or the lead with lead merge on');
  assert.ok(!/push/.test(rw.replace(/pushed/g, '')), 'never pushes (no force)');
});

test('lead releases and tags: switch, Next version, version file, not existing', () => {
  const okArgs = { kind: 'release', leadActions: true, switchOn: true, requested: 'v0.9.0', next: '0.9.0', fileVer: '0.9.0', exists: false };
  assert.deepEqual(rel.checkLead(okArgs), { ok: true, version: '0.9.0', tag: 'v0.9.0' });
  assert.match(rel.checkLead({ ...okArgs, switchOn: false }).reason, /switch is off/);
  assert.match(rel.checkLead({ ...okArgs, leadActions: false }).reason, /lead switch is off/);
  assert.match(rel.checkLead({ ...okArgs, requested: 'v0.9.1' }).reason, /only v0\.9\.0/);
  assert.match(rel.checkLead({ ...okArgs, fileVer: '0.8.0' }).reason, /version file on main says 0\.8\.0/);
  assert.match(rel.checkLead({ ...okArgs, exists: true }).reason, /already has a release/);
  assert.match(rel.checkLead({ ...okArgs, kind: 'tag', requested: 'v1.0.0' }).reason, /only v0\.9\.0/);
  assert.equal(rel.fileVersion('package.json', '{"version":"0.9.0"}'), '0.9.0');
  assert.equal(rel.fileVersion('VERSION', '0.6.52\n'), '0.6.52');
  assert.deepEqual(rel.pushTagArgs('0.9.0'), ['push', 'origin', 'refs/tags/v0.9.0']);
  assert.ok(!rel.pushTagArgs('0.9.0').some((a) => /force|-f|delete|:refs/.test(a)));
  const projects = require('../electron/ops/projects.cjs');
  assert.equal(projects.cleanSettings({ nextVersion: '0.9.0' }).nextVersion, '0.9.0');
  assert.equal(projects.cleanSettings({ nextVersion: 'v1; rm' }).nextVersion, '');
  assert.equal(projects.defaultSettings().nextVersion, '', 'no Next version until the owner sets one');
});
